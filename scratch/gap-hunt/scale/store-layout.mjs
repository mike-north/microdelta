import Database from 'better-sqlite3';
import { copyFileSync, statSync } from 'node:fs';
import { performance } from 'node:perf_hooks';
const source = process.argv[2] ?? 'scratch/gap-hunt/scale/payload-20000.sqlite';
const copy = 'scratch/gap-hunt/scale/vacuum-copy.sqlite';
copyFileSync(source, copy);
const db = new Database(copy);
const before = statSync(copy).size;
const counts = Object.fromEntries(['history_results', 'history_nodes', 'history_edges', 'history_addresses'].map(table => [table, db.prepare(`SELECT COUNT(*) AS count FROM ${table}`).get().count]));
const pages = db.prepare('PRAGMA page_count').get();
const free = db.prepare('PRAGMA freelist_count').get();
const start = performance.now();
db.exec('VACUUM');
const milliseconds = performance.now() - start;
db.close();
console.log(JSON.stringify({ counts, pages, free, before, after: statSync(copy).size, vacuumMilliseconds: milliseconds }));
const history = new Database(process.argv[3] ?? 'scratch/gap-hunt/scale/context-resolve-plain.sqlite', { readonly: true });
console.log(JSON.stringify({ results: history.prepare('SELECT COUNT(*) AS count FROM history_results').get(), acceptances: history.prepare('SELECT COUNT(*) AS count FROM history_acceptances').get() }));
history.close();
